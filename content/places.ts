export function getPlace(slug: string): Place | undefined {
  return places.find((place) => place.slug === slug);
}

export function placeNeighbors(slug: string): { prev?: Place; next?: Place } {
  const index = places.findIndex((place) => place.slug === slug);
  return {
    prev: index > 0 ? places[index - 1] : undefined,
    next: index >= 0 && index < places.length - 1 ? places[index + 1] : undefined,
  };
}
