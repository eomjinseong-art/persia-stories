export function getWar(slug: string): War | undefined {
  return wars.find((war) => war.slug === slug);
}

export function warNeighbors(slug: string): { prev?: War; next?: War } {
  const index = wars.findIndex((war) => war.slug === slug);
  return {
    prev: index > 0 ? wars[index - 1] : undefined,
    next: index >= 0 && index < wars.length - 1 ? wars[index + 1] : undefined,
  };
}
