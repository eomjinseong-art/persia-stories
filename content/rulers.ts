export function getRuler(slug: string): Ruler | undefined {
  return rulers.find((ruler) => ruler.slug === slug);
}

export function rulerNeighbors(slug: string): {
  prev?: Ruler;
  next?: Ruler;
} {
  const index = rulers.findIndex((ruler) => ruler.slug === slug);
  return {
    prev: index > 0 ? rulers[index - 1] : undefined,
    next: index >= 0 && index < rulers.length - 1 ? rulers[index + 1] : undefined,
  };
}
